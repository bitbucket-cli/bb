// Command homebrew generates a tap formula from verified release archives.
// It writes a local file only; publishing belongs to the release workflow.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"text/template"
)

var versionPattern = regexp.MustCompile(`^v[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?$`)
var repositoryPattern = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_.-]*/[A-Za-z0-9][A-Za-z0-9_.-]*$`)
var targets = []string{"darwin_amd64", "darwin_arm64", "linux_amd64", "linux_arm64"}

func main() {
	version := flag.String("version", "", "release tag, e.g. v1.2.3")
	repository := flag.String("repository", "bitbucket-cli/bb", "GitHub owner/repository containing the release")
	checksums := flag.String("checksums", "dist/checksums.txt", "GoReleaser checksums file; archives must be alongside it")
	output := flag.String("output", "dist/homebrew/bb.rb", "local formula output path")
	flag.Parse()
	if err := run(*version, *repository, *checksums, *output); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(version, repository, manifest, output string) error {
	data, err := os.ReadFile(manifest)
	if err != nil {
		return err
	}
	formula, hashes, err := generate(version, repository, bytes.NewReader(data))
	if err != nil {
		return err
	}
	// Match the actual archives rather than trusting a stale checksum manifest.
	for _, target := range targets {
		name := "bb_" + target + ".tar.gz"
		archive, err := os.Open(filepath.Join(filepath.Dir(manifest), name))
		if err != nil {
			return err
		}
		hash := sha256.New()
		_, err = io.Copy(hash, archive)
		closeErr := archive.Close()
		if err != nil {
			return err
		}
		if closeErr != nil {
			return closeErr
		}
		if hex.EncodeToString(hash.Sum(nil)) != hashes[target] {
			return fmt.Errorf("archive checksum mismatch: %s", name)
		}
	}
	if err := os.MkdirAll(filepath.Dir(output), 0755); err != nil {
		return err
	}
	return os.WriteFile(output, formula, 0644)
}

func generate(version, repository string, manifest io.Reader) ([]byte, map[string]string, error) {
	if !versionPattern.MatchString(version) {
		return nil, nil, fmt.Errorf("invalid release tag %q; expected vMAJOR.MINOR.PATCH with optional prerelease", version)
	}
	if !repositoryPattern.MatchString(repository) {
		return nil, nil, fmt.Errorf("invalid GitHub repository %q; expected owner/repository", repository)
	}
	sums := map[string]string{}
	scanner := bufio.NewScanner(manifest)
	for scanner.Scan() {
		if strings.TrimSpace(scanner.Text()) == "" {
			continue
		}
		fields := strings.Fields(scanner.Text())
		if len(fields) != 2 {
			return nil, nil, fmt.Errorf("invalid checksum line")
		}
		sum, err := hex.DecodeString(fields[0])
		if err != nil || len(sum) != sha256.Size {
			return nil, nil, fmt.Errorf("invalid SHA256 checksum for %s", fields[1])
		}
		name := strings.TrimPrefix(fields[1], "*")
		if _, exists := sums[name]; exists {
			return nil, nil, fmt.Errorf("duplicate checksum entry for %s", name)
		}
		sums[name] = strings.ToLower(fields[0])
	}
	if err := scanner.Err(); err != nil {
		return nil, nil, err
	}
	hashes := map[string]string{}
	for _, target := range targets {
		name := "bb_" + target + ".tar.gz"
		if sums[name] == "" {
			return nil, nil, fmt.Errorf("missing checksum for %s", name)
		}
		hashes[target] = sums[name]
	}
	tmpl, err := template.New("formula").Parse(formulaTemplate)
	if err != nil {
		return nil, nil, err
	}
	var out bytes.Buffer
	err = tmpl.Execute(&out, struct {
		Tag, Version, Repository string
		Hashes                   map[string]string
	}{version, strings.TrimPrefix(version, "v"), repository, hashes})
	return out.Bytes(), hashes, err
}

const formulaTemplate = `# typed: strict
# frozen_string_literal: true

# Generated by bb's scripts/homebrew. Do not edit by hand.
class Bb < Formula
  desc "Bitbucket CLI for repositories, pull requests, and pipelines"
  homepage "https://github.com/{{.Repository}}"
  version "{{.Version}}"
  license "MIT"

  on_macos do
    on_intel do
      url "https://github.com/{{.Repository}}/releases/download/{{.Tag}}/bb_darwin_amd64.tar.gz"
      sha256 "{{index .Hashes "darwin_amd64"}}"
    end
    on_arm do
      url "https://github.com/{{.Repository}}/releases/download/{{.Tag}}/bb_darwin_arm64.tar.gz"
      sha256 "{{index .Hashes "darwin_arm64"}}"
    end
  end

  on_linux do
    on_intel do
      url "https://github.com/{{.Repository}}/releases/download/{{.Tag}}/bb_linux_amd64.tar.gz"
      sha256 "{{index .Hashes "linux_amd64"}}"
    end
    on_arm do
      url "https://github.com/{{.Repository}}/releases/download/{{.Tag}}/bb_linux_arm64.tar.gz"
      sha256 "{{index .Hashes "linux_arm64"}}"
    end
  end

  def install
    bin.install "bb"
    doc.install "README.md", "LICENSE", "THIRD_PARTY_LICENSES.txt"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/bb --version")
  end
end
`
