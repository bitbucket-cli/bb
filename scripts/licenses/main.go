// Command licenses collects upstream licence and notice files for release binaries.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

type module struct {
	Path, Version, Dir string
	Main               bool
	Replace            *module
}
type dependency struct {
	Standard bool
	Module   *module
}

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	modules := map[string]module{}
	for _, target := range []string{"linux/amd64", "linux/arm64", "darwin/amd64", "darwin/arm64", "windows/amd64", "windows/arm64"} {
		pair := strings.Split(target, "/")
		cmd := exec.Command("go", "list", "-mod=readonly", "-deps", "-json", "./cmd/bb")
		cmd.Env = append(os.Environ(), "GOOS="+pair[0], "GOARCH="+pair[1], "CGO_ENABLED=0")
		cmd.Stderr = os.Stderr
		data, err := cmd.Output()
		if err != nil {
			return fmt.Errorf("list %s: %w", target, err)
		}
		dec := json.NewDecoder(bytes.NewReader(data))
		for {
			var dep dependency
			if err := dec.Decode(&dep); err == io.EOF {
				break
			} else if err != nil {
				return err
			}
			if dep.Module == nil || dep.Module.Main {
				continue
			}
			mod := *dep.Module
			if mod.Replace != nil {
				return fmt.Errorf("cannot attribute replacement module %s automatically", mod.Path)
			}
			modules[mod.Path] = mod
		}
	}
	var out bytes.Buffer
	out.WriteString("THIRD-PARTY LICENCES AND NOTICES\n\nGenerated by go run ./scripts/licenses; do not edit by hand.\nIncludes modules linked by any CGO-disabled release target, plus the Go runtime\nand notices shipped with its vendored dependencies. Extra upstream notices may\ncover files not linked into bb. The project licence is distributed separately.\n\n")
	goroot, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return err
	}
	goversion, err := exec.Command("go", "env", "GOVERSION").Output()
	if err != nil {
		return err
	}
	root := strings.TrimSpace(string(goroot))
	if err := appendFiles(&out, "Go runtime "+strings.TrimSpace(string(goversion)), root, false); err != nil {
		return err
	}
	if err := appendFiles(&out, "Go vendored dependencies", filepath.Join(root, "src", "vendor"), true); err != nil {
		return err
	}
	paths := make([]string, 0, len(modules))
	for path := range modules {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		mod := modules[path]
		if err := appendFiles(&out, mod.Path+" "+mod.Version, mod.Dir, true); err != nil {
			return err
		}
	}
	return os.WriteFile("THIRD_PARTY_LICENSES.txt", out.Bytes(), 0644)
}

func appendFiles(out *bytes.Buffer, label, root string, recursive bool) error {
	var paths []string
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			if path != root && (!recursive || entry.Name() == ".git") {
				return filepath.SkipDir
			}
			return nil
		}
		name := strings.ToUpper(entry.Name())
		if strings.Contains(name, "LICENSE") || strings.Contains(name, "LICENCE") || name == "COPYING" || strings.HasPrefix(name, "COPYING.") || name == "NOTICE" || strings.HasPrefix(name, "NOTICE.") || name == "PATENTS" || name == "COPYRIGHT" || name == "AUTHORS" {
			paths = append(paths, path)
		}
		return nil
	})
	if err != nil {
		return err
	}
	if len(paths) == 0 {
		return fmt.Errorf("no licence or notice found for %s in %s; review attribution manually", label, root)
	}
	sort.Strings(paths)
	for _, path := range paths {
		content, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		fmt.Fprintf(out, "==============================================================================\n%s — %s\n==============================================================================\n", label, filepath.ToSlash(rel))
		out.Write(content)
		out.WriteString("\n\n")
	}
	return nil
}
